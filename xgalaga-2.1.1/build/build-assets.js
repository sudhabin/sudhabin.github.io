/*
 * build-assets.js - embeds the original XGalaga data files into js/assets.js
 * so the browser game can run from file:// with no web server.
 *
 * Usage:  node build/build-assets.js
 *
 * Reads from ../xgalaga-2.1.1.0 (images/*.xpm, levels/*.xgl, sounds/*.raw)
 * and writes js/assets.js.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.resolve(ROOT, '..', 'xgalaga-2.1.1.0');
const OUT = path.join(ROOT, 'js', 'assets.js');

function readDir(dir, filter) {
  return fs.readdirSync(dir).filter(filter).sort();
}

function xpm(name, rows, color) {
  return [
    '/* XPM */',
    'static char *' + name + '_xpm[] = {',
    '"15 10 2 1",',
    '"  c None",',
    '"X c #' + color + '",',
    ...rows.map((r) => '"' + r + '",'),
    '};',
    '',
  ].join('\n');
}

function main() {
  if (!fs.existsSync(SRC)) {
    console.error('Source directory not found: ' + SRC);
    process.exit(1);
  }

  const images = {};
  for (const file of readDir(path.join(SRC, 'images'), (f) => f.endsWith('.xpm'))) {
    images[path.basename(file, '.xpm')] = fs.readFileSync(path.join(SRC, 'images', file), 'utf8');
  }

  // XGalaga 2.1.1 references pr_spread / pr_machine prizes, but those XPMs
  // are not in the release tarball.  Draw simple stand-ins in the same style.
  if (!images.pr_spread) {
    images.pr_spread = xpm('pr_spread', [
      '       X       ',
      '      XXX      ',
      '     X X X     ',
      '    X  X  X    ',
      '   X   X   X   ',
      '  X    X    X  ',
      '       X       ',
      '       X       ',
      '               ',
      '               ',
    ], '00FFFF');
  }
  if (!images.pr_machine) {
    images.pr_machine = xpm('pr_machine', [
      '               ',
      '     X   X     ',
      '     X   X     ',
      '     X   X     ',
      '     X   X     ',
      '     X   X     ',
      '     X   X     ',
      '               ',
      '               ',
      '               ',
    ], 'FFFF00');
  }

  const levels = {};
  for (const file of readDir(path.join(SRC, 'levels'), (f) => /^level\d+\.xgl$/.test(f))) {
    levels[path.basename(file, '.xgl')] = fs.readFileSync(path.join(SRC, 'levels', file), 'utf8');
  }

  const sounds = {};
  for (const file of readDir(path.join(SRC, 'sounds'), (f) => f.endsWith('.raw'))) {
    sounds[path.basename(file, '.raw')] = fs.readFileSync(path.join(SRC, 'sounds', file)).toString('base64');
  }

  const data = {
    source: 'XGalaga 2.1.1 by Joe Rumsey (GPL v2)',
    images,
    levels,
    sounds,
  };

  const body =
    '/* Generated by build/build-assets.js - do not edit by hand.\n' +
    ' * Artwork, levels and sounds are from XGalaga 2.1.1 (GPL v2).\n' +
    ' */\n' +
    'window.XGALAGA_ASSETS = ' +
    JSON.stringify(data) +
    ';\n';

  fs.writeFileSync(OUT, body, 'utf8');

  const kb = (n) => (n / 1024).toFixed(1) + ' KB';
  console.log('Wrote ' + OUT);
  console.log('  images: ' + Object.keys(images).length + ' (' + kb(fs.statSync(OUT).size) + ' total file)');
  console.log('  levels: ' + Object.keys(levels).length);
  console.log('  sounds: ' + Object.keys(sounds).length);
}

main();
